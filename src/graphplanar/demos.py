"""Готовые графы для демонстрации и тестов."""

from itertools import combinations


def complete(n):
    return [(u, v) for u, v in combinations(range(1, n + 1), 2)]


def complete_bipartite(a, b):
    return [(u, v) for u in range(1, a + 1) for v in range(a + 1, a + b + 1)]


def cycle(n):
    return [(i, i % n + 1) for i in range(1, n + 1)]


def wheel(n):
    """Колесо: центр 1 и обод из n вершин."""
    rim = [(v, v + 1) for v in range(2, n + 1)] + [(n + 1, 2)]
    return [(1, v) for v in range(2, n + 2)] + rim


def grid(rows, cols):
    def vid(r, c):
        return r * cols + c + 1
    edges = []
    for r in range(rows):
        for c in range(cols):
            if c + 1 < cols:
                edges.append((vid(r, c), vid(r, c + 1)))
            if r + 1 < rows:
                edges.append((vid(r, c), vid(r + 1, c)))
    return edges


